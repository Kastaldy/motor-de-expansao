/**
 * Os dois hex-maps do Início, em forma COMPACTA.
 *
 * Eles vêm do mockup de design ("Início · Expansão + Operações"), que os exportou como
 * ~360 `<polygon>` cada, com os seis vértices escritos por extenso e a cor turquesa
 * cravada em `rgba()` — 62 KB por ilustração, e nenhuma das duas sobreviveria ao tema
 * claro. Aqui fica só o que não dá para derivar: o CENTRO de cada hexágono e a sua
 * opacidade. A geometria é regular (hexágono de topo pontudo), então os vértices se
 * reconstroem no render a partir do raio — e a cor passa a ser `var(--ac)`, que segue
 * o tema como o resto do app.
 *
 * Formato: `"cx,cy,alfa;"` por hexágono, num texto só. Lista de objetos custaria ~4x
 * mais bytes de fonte para o mesmo desenho; `analisarHexes` desdobra uma vez, na carga
 * do módulo. Coordenadas no sistema do `viewBox` 240x150 do mockup.
 *
 * Alfa `1` = hexágono CHEIO: no mockup são as unidades Ultra já instaladas.
 */

export interface HexArte {
  cx: number
  cy: number
  alfa: number
}

/** Desdobra o texto compacto na lista que o render consome. */
export function analisarHexes(plano: string): readonly HexArte[] {
  return plano
    .split(';')
    .map((p) => p.trim())
    .filter(Boolean)
    .map((p) => {
      const [cx, cy, alfa] = p.split(',').map(Number)
      return { cx, cy, alfa }
    })
}

